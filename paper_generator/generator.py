CJK_PATTERN = re.compile(
    r"[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7a3]"
)


def _normalize_topic(topic: str) -> str:
    topic = html.unescape(topic or "")
    topic = unicodedata.normalize(
        "NFKC",
        topic,
    )

    topic = topic.replace(
        "\xa0",
        " ",
    )

    topic = topic.strip().strip(
        '"“”\'‘’'
    )

    topic = re.sub(
        r"[ \t]+",
        " ",
        topic,
    )

    topic = re.sub(
        r"\s*\n\s*",
        " ",
        topic,
    )

    return topic.strip()


def _clean_text(text: str) -> str:
    text = unicodedata.normalize(
        "NFKC",
        text or "",
    )

    text = html.unescape(text)

    text = text.replace(
        "\xa0",
        " ",
    )

    # Markdown heading 제거
    text = re.sub(
        r"(?m)^\s*#{1,6}\s*",
        "",
        text,
    )

    # 번호 / bullet 제거
    text = re.sub(
        r"(?m)^\s*(?:[-*]|\d+[.)]|[IVXLCDM]+[.)])\s+",
        "",
        text,
    )

    # Sentence 1: 같은 라벨 제거
    text = re.sub(
        r"(?i)\bSentence\s+\d+\s*:\s*",
        "",
        text,
    )

    # URL 제거
    text = re.sub(
        r"https?://\S+",
        "",
        text,
    )

    # DOI 제거
    text = re.sub(
        r"\bdoi\s*:\s*\S+",
        "",
        text,
        flags=re.IGNORECASE,
    )

    # 임의 인용 제거
    text = re.sub(
        r"\[(?:\d+)(?:\s*[-–,]\s*\d+)*\]",
        "",
        text,
    )

    # 공백 정리
    text = re.sub(
        r"[ \t]+",
        " ",
        text,
    )

    text = re.sub(
        r"\n{2,}",
        "\n",
        text,
    )

    return text.strip()


def _trim_complete_sentence(
    text: str,
    limit: int,
) -> str:
    text = _clean_text(
        text
    )

    if len(text) <= limit:
        return text

    cut = text[:limit]

    sentence_ends = [
        match.end()
        for match in re.finditer(
            r"[.!?](?=\s|$)",
            cut,
        )
    ]

    if sentence_ends:
        return cut[
            :max(sentence_ends)
        ].strip()

    space_pos = cut.rfind(
        " "
    )

    if space_pos > 0:
        return cut[
            :space_pos
        ].strip()

    return cut.strip()


def _contains_fact_risk(text: str) -> bool:
    for pattern in FACT_RISK_PATTERNS:
        if re.search(
            pattern,
            text,
            flags=re.IGNORECASE,
        ):
            return True

    return False


def _contains_semantic_risk(text: str) -> bool:
    for pattern in SEMANTIC_RISK_PATTERNS:
        if re.search(
            pattern,
            text,
            flags=re.IGNORECASE,
        ):
            return True

    return False


def _contains_cjk(text: str) -> bool:
    return bool(
        CJK_PATTERN.search(
            text
        )
    )


def _looks_corrupted(text: str) -> bool:
    """
    exa mined / th e / c opyr 같은
    단어 붕괴 탐지.
    """

    single_letters = re.findall(
        r"\b[b-hj-zB-HJ-Z]\b",
        text,
    )

    if len(single_letters) >= 2:
        return True

    broken_sequences = re.findall(
        r"\b[A-Za-z]{1,2}\s+"
        r"[A-Za-z]{1,2}\s+"
        r"[A-Za-z]{1,2}\b",
        text,
    )

    if len(
        broken_sequences
    ) >= 2:
        return True

    return False


def _sentence_count(text: str) -> int:
    text = text.strip()

    if not text:
        return 0

    sentences = re.split(
        r"(?<=[.!?])\s+(?=[A-Z])",
        text,
    )

    sentences = [
        sentence.strip()
        for sentence in sentences
        if sentence.strip()
    ]

    return len(
        sentences
    )


def _is_safe_output(
    text: str,
    section: str,
) -> bool:
    if not text.strip():
        return False

    # 사건 사실 환각
    if _contains_fact_risk(
        text
    ):
        return False

    # AI-generated music로 의미 뒤집힘
    if _contains_semantic_risk(
        text
    ):
        return False

    # 한중일 문자 혼용
    if _contains_cjk(
        text
    ):
        return False

    # 텍스트 깨짐
    if _looks_corrupted(
        text
    ):
        return False

    if section != "title":

        # 문장 완결성
        if text[-1] not in ".!?":
            return False

        # section별 문장 수
        expected = (
            EXPECTED_SENTENCE_COUNTS.get(
                section
            )
        )

        if expected is not None:
            actual = _sentence_count(
                text
            )

            if actual != expected:
                return False

    return True


