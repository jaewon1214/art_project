class PaperDraftGenerator:
    """
    입력:
        한국어 연구 주제

    출력:
        영어 논문 구조 초안

    허용:
        - 사용자 입력에 명시된 사건명
        - 사건을 연구 중심 사례로 지정
        - 연구 목적 / 연구 질문 / 분석 구조

    금지:
        - 사건 날짜
        - 당사자 실제 행위
        - 당사자 주장
        - 소송 경위
        - 판결
        - 통계
        - 출처
        - 최종 법적 결론
    """

    def __init__(self):
        if not ADAPTER_DIR.exists():
            raise FileNotFoundError(
                f"LoRA adapter not found: {ADAPTER_DIR}"
            )

        if not torch.cuda.is_available():
            raise RuntimeError(
                "CUDA GPU is not available."
            )

        self.tokenizer = (
            AutoTokenizer.from_pretrained(
                str(
                    ADAPTER_DIR
                ),
                trust_remote_code=True,
                use_fast=True,
            )
        )

        if (
            self.tokenizer.pad_token_id
            is None
        ):
            self.tokenizer.pad_token = (
                self.tokenizer.eos_token
            )

        base_model = (
            AutoModelForCausalLM.from_pretrained(
                BASE_MODEL,
                dtype=torch.float16,
                device_map="cuda",
                low_cpu_mem_usage=True,
                trust_remote_code=True,
            )
        )

        self.model = (
            PeftModel.from_pretrained(
                base_model,
                str(
                    ADAPTER_DIR
                ),
            )
        )

        self.model.eval()

    def _build_prompt(
        self,
        topic: str,
        section: str,
        retry: bool = False,
    ) -> str:
        cfg = SECTION_CONFIG[
            section
        ]

        retry_text = ""

        if retry:
            retry_text = """
Your previous answer was rejected.

Follow these rules strictly:

The case name explicitly provided by the user may be used
only as the central case or scope of the research.

Do not generate facts about the case.

Do not generate:
dates,
party actions,
party claims,
allegations,
procedural history,
court rulings,
statistics,
or legal outcomes.

Do not reinterpret copyrighted musical works
as AI-generated music.

Write only the academic research structure.

Follow the exact requested sentence count.
"""

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": (
                    f"{cfg['instruction']}\n\n"
                    f"{retry_text}\n\n"
                    f"User research topic:\n"
                    f"{topic}\n\n"
                    "The topic is written in Korean. "
                    "Understand it faithfully, but answer only in English. "
                    "The real case name explicitly provided by the user "
                    "may be preserved as the central case of the research. "
                    "However, do not add factual information about that case. "
                    "All case facts must remain subjects for external verification. "
                    "When the topic concerns 음악저작물을 AI 학습데이터로 이용, "
                    "interpret it as copyrighted musical works used as "
                    "training data for generative AI. "
                    "Never reinterpret it as AI-generated music."
                ),
            },
        ]

        return (
            self.tokenizer.apply_chat_template(
                messages,
                tokenize=False,
                add_generation_prompt=True,
            )
        )

    @torch.inference_mode()
    def _run_generation(
        self,
        topic: str,
        section: str,
        retry: bool = False,
    ) -> str:
        cfg = SECTION_CONFIG[
            section
        ]

        prompt = self._build_prompt(
            topic,
            section,
            retry,
        )

        inputs = self.tokenizer(
            prompt,
            return_tensors="pt",
        ).to(
            "cuda"
        )

        outputs = self.model.generate(
            **inputs,

            max_new_tokens=cfg[
                "max_new_tokens"
            ],

            do_sample=False,

            repetition_penalty=1.05,

            pad_token_id=(
                self.tokenizer.eos_token_id
            ),

            eos_token_id=(
                self.tokenizer.eos_token_id
            ),
        )

        generated = outputs[
            0,
            inputs[
                "input_ids"
            ].shape[1]:
        ]

        text = (
            self.tokenizer.decode(
                generated,
                skip_special_tokens=True,
            )
        )

        return (
            _trim_complete_sentence(
                text,
                cfg[
                    "char_limit"
                ],
            )
        )

    def _generate_section(
        self,
        topic: str,
        section: str,
    ) -> str:
        # 1차 생성
        text = self._run_generation(
            topic,
            section,
            retry=False,
        )

        if _is_safe_output(
            text,
            section,
        ):
            return text

        # 2차 생성
        retry_text = self._run_generation(
            topic,
            section,
            retry=True,
        )

        if _is_safe_output(
            retry_text,
            section,
        ):
            return retry_text

        # 두 번 실패하면 안전한 구조 문장 반환
        return _safe_fallback(
            section
        )

    def generate_draft(
        self,
        topic: str,
    ) -> dict:
        topic = _normalize_topic(
            topic
        )

        if not topic:
            raise ValueError(
                "topic must not be empty."
            )

        draft = {
            "title": (
                self._generate_section(
                    topic,
                    "title",
                ).strip(
                    '"“”'
                )
            ),

            "abstract": (
                self._generate_section(
                    topic,
                    "abstract",
                )
            ),

            "introduction": (
                self._generate_section(
                    topic,
                    "introduction",
                )
            ),

            "body": (
                self._generate_section(
                    topic,
                    "body",
                )
            ),

            "conclusion": (
                self._generate_section(
                    topic,
                    "conclusion",
                )
            ),
        }

        return draft


_generator: PaperDraftGenerator | None = None


def get_generator() -> PaperDraftGenerator:
    global _generator

    if _generator is None:
        _generator = (
            PaperDraftGenerator()
        )

    return _generator


def generate_draft(
    topic: str,
) -> dict:
    """
    Backend 공개 인터페이스.

    입력:
        한국어 연구 주제

    출력:
        영어 구조 초안

    반환 형식:
    {
        "title": str,
        "abstract": str,
        "introduction": str,
        "body": str,
        "conclusion": str
    }
    """

    return get_generator().generate_draft(
        topic
    )


